import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { root, verify } from './verify-frontend.mjs';
await verify();
const bytes = await readFile(new URL('public/Square One.dc.html', root));
await mkdir(new URL('lib/generated/', root), { recursive: true });
await writeFile(new URL('lib/generated/page-html.js', root), '// Generated by npm run build. Do not edit.\nexport const HTML = ' + JSON.stringify(bytes.toString('utf8')) + ';\nexport const HTML_SHA256 = ' + JSON.stringify(createHash('sha256').update(bytes).digest('hex')) + ';\n');
